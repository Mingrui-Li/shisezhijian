import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const source = resolve(root, 'assets/design/design-tokens.json');
const output = resolve(root, 'game/assets/scripts/theme/Theme.ts');
const tokens = JSON.parse(readFileSync(source, 'utf8'));
const value = {
  colors: tokens.colors,
  spacing: tokens.spacing,
  radii: tokens.radii,
  typography: {
    family: tokens.typography.family,
    ...Object.fromEntries(['title', 'chapter', 'body', 'button', 'caption', 'moves'].map(k => [k, tokens.typography[k].size])),
  },
  controls: tokens.controls,
  board: Object.fromEntries(['preferredCellSize', 'minimumVisibleCellSize', 'preferredGap', 'minimumGap', 'maximumColumns', 'maximumRows', 'trayColumns', 'trayRowsPerPage', 'trayPageSize'].map(k => [k, tokens.board[k]])),
  motion: Object.fromEntries(['pressMs', 'placementMs', 'modalMs', 'completeMs'].map(k => [k, tokens.motion[k]])),
};
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, '// Generated by tools/design/sync-theme.mjs from design-tokens.json. Do not edit.\n' +
  '// Puzzle tile faces always use exact level HEX, never this theme palette.\n' +
  `export const theme = ${JSON.stringify(value, null, 2)} as const;\n`);
console.log('Click-fill theme synchronized to game/assets/scripts/theme/Theme.ts');
